    /// <summary>
    /// f9-predkosc: rejestracja UIExtenderEx (jedyne typy Armoury zalezne od Bannerlord.UIExtenderEx - wolane przez metode NoInlining w SubModuleMain,
    /// wiec brak zestawu UIExtenderEx konczy sie linia w logu, nie bledem calego modulu). Tylko dwa typy: wstawka do prefabu MapBar i mixin
    /// MapTimeControlVM. UIExtenderEx sam wylacza gotowy (AutoGenerated) kod prefabu MapBar, gdy ruch ma wstawke (GauntletMoviePatch; konstruktor atrybutu
    /// z nazwa AutoGen jest w tej wersji przestarzaly - "AutoGens are globally disabled").
    /// </summary>
    internal static class MapSpeedUi
    {
        private static bool _done;
        internal static string State = "nierejestrowane";

        internal static void Register()
        {
            if (_done) return;
            _done = true;
            var ext = UIExtender.Create("Armoury");
            ext.Register(new[] { typeof(MapSpeedBarExtension), typeof(MapSpeedMixin) });
            ext.Enable();
            State = "wstawka MapBar i mixin MapTimeControlVM zarejestrowane";
            Log.Info("Predkosc mapy (f9): UIExtenderEx - " + State + ".");
        }
    }

    /// <summary>
    /// f9: wstawka do prefabu MapBar (SandBox\GUI\Prefabs\Map\MapBar.xml) jako SIOSTRA srodkowego panelu (MapCurrentTimeVisualWidget Id="CenterPanel") -
    /// nie jego dziecko: Gauntlet zbiera klik tylko z widzetow, ktorych wszyscy przodkowie zawieraja punkt (EventManager.CollectEnableWidgetsAt), a panel ma
    /// 430 x 59, a przyciski stoja nad nim. Pas 430 x 28 wysrodkowany jak panel, tuz nad nim (MarginBottom 59), przyciski po prawej - nad pauza / play / >>
    /// gry (x 275-372 panelu), lewo od kola pory dnia. Pas i tlo bez zdarzen (klik obok przyciskow idzie do mapy). Przycisk jak przyciski czasu gry:
    /// ButtonWidget + HintWidget IsDisabled (podpowiedz na najechaniu, klik do przycisku). Pedzle gry: MapBar.Left.Button (stany, bez obrazka),
    /// MapTextBrushGal (czcionka daty paska). Napis wybranego biegu zloty (#FFC349 - kolor zaznaczenia przyciskow paska), pozostale szare.
    /// </summary>
    [PrefabExtension("MapBar", "descendant::MapCurrentTimeVisualWidget[@Id='CenterPanel']")]
    internal sealed class MapSpeedBarExtension : PrefabExtensionInsertPatch
    {
        private readonly List<XmlNode> _nodes;
        public override InsertType Type => InsertType.Append;

        [PrefabExtensionXmlNodes]
        public IEnumerable<XmlNode> Nodes => _nodes;

        private static string Button(string cmd, string on, string text, string hint)
        {
            const string label = "WidthSizePolicy=\"StretchToParent\" HeightSizePolicy=\"StretchToParent\" Brush=\"MapTextBrushGal\" Brush.FontSize=\"18\" "
                               + "Brush.TextHorizontalAlignment=\"Center\" Brush.TextVerticalAlignment=\"Center\" ";
            return "<ButtonWidget WidthSizePolicy=\"Fixed\" HeightSizePolicy=\"Fixed\" SuggestedWidth=\"36\" SuggestedHeight=\"26\" Brush=\"MapBar.Left.Button\" "
                 + "Command.Click=\"" + cmd + "\" UpdateChildrenStates=\"true\"><Children>"
                 + "<TextWidget DoNotAcceptEvents=\"true\" " + label + "Brush.FontColor=\"#FFC349FF\" Text=\"@" + text + "\" IsVisible=\"@" + on + "\" />"
                 + "<TextWidget DoNotAcceptEvents=\"true\" " + label + "Brush.FontColor=\"#C8C8C8FF\" Text=\"@" + text + "\" IsHidden=\"@" + on + "\" />"
                 + "<HintWidget DataSource=\"{" + hint + "}\" WidthSizePolicy=\"StretchToParent\" HeightSizePolicy=\"StretchToParent\" "
                 + "Command.HoverBegin=\"ExecuteBeginHint\" Command.HoverEnd=\"ExecuteEndHint\" IsDisabled=\"true\" />"
                 + "</Children></ButtonWidget>";
        }

        public MapSpeedBarExtension()
        {
            var xml =
                "<Widget Id=\"ArmMapSpeed\" DataSource=\"{MapTimeControl}\" DoNotAcceptEvents=\"true\" WidthSizePolicy=\"Fixed\" HeightSizePolicy=\"Fixed\" "
              + "SuggestedWidth=\"430\" SuggestedHeight=\"28\" HorizontalAlignment=\"Center\" VerticalAlignment=\"Bottom\" MarginBottom=\"59\"><Children>"
              + "<ListPanel DataSource=\"{ArmSpeed}\" IsVisible=\"@IsShown\" DoNotAcceptEvents=\"true\" WidthSizePolicy=\"CoverChildren\" HeightSizePolicy=\"Fixed\" "
              + "SuggestedHeight=\"26\" HorizontalAlignment=\"Right\" VerticalAlignment=\"Bottom\" MarginRight=\"44\" StackLayout.LayoutMethod=\"HorizontalLeftToRight\" "
              + "Sprite=\"BlankWhiteSquare_9\" Color=\"#000000A0\"><Children>"
              + Button("ExecuteSpeed1", "Is1On", "Text1", "Hint1")
              + Button("ExecuteSpeedFast", "IsFastOn", "TextFast", "HintFast")
              + Button("ExecuteSpeedVeryFast", "IsVeryFastOn", "TextVeryFast", "HintVeryFast")
              + "</Children></ListPanel>"
              + "</Children></Widget>";
            var doc = new XmlDocument();
            doc.LoadXml(xml);
            _nodes = new List<XmlNode> { doc };
        }
    }

    /// <summary>f9: mixin MapTimeControlVM - jedna wlasciwosc ArmSpeed (nasz ViewModel przyciskow); rejestracja VM do postfiksu Tick, zwolnienie przy OnFinalize.</summary>
    [ViewModelMixin]
    internal sealed class MapSpeedMixin : BaseViewModelMixin<MapTimeControlVM>
    {
        private readonly ArmMapSpeedVM _vm;
        private readonly MapTimeControlVM _owner;

        public MapSpeedMixin(MapTimeControlVM vm) : base(vm)
        {
            _owner = vm;
            _vm = new ArmMapSpeedVM(vm);
            MapSpeed.Attach(vm, _vm);
        }

        [DataSourceProperty]
        public ArmMapSpeedVM ArmSpeed => _vm;

        public override void OnFinalize()
        {
            base.OnFinalize();
            try { MapSpeed.Detach(_owner, _vm); _vm.OnFinalize(); } catch (Exception e) { Log.Error("MapSpeedMixin.OnFinalize", e); }
        }
    }
