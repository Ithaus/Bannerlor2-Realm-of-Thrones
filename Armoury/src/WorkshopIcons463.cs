    /// <summary>
    /// 463 (Jeff 12.11: "daj warsztatom storz ikony bo niektore maja a niektore maja jakas niebieski prostokat"): ikony typow warsztatow BK.
    /// Dowod (SandBox/ROT-Content GUI/Brushes/Clan.xml, dekompilacja ClanWorkshopTypeVisualBrushWidget): ikona w finansach rodu
    /// (ClanIncomeTuple), w oknie zmiany produkcji (ClanCardSelectionPopup) i w encyklopedii osady BK (SettlementEncyclopediaExtension)
    /// to pedzel "Clan.Workshop.Type.Image", a widzet robi SetState(StringId typu). Pedzel ma style tylko dla 11 typow gry; dla typu bez stylu
    /// Brush.GetStyleOrDefault daje styl Default = warstwa BlankWhiteSquare_9 w kolorze #2168DD (niebieski prostokat). Ten sam prostokat ma jawnie
    /// styl "artisans". Typy BK (workshops.xml): weaponsmithy, armorsmithy, barding-smithy, fletcher, bakery, butcher, mines, meadery - bez stylu.
    /// Ekran zarzadzania miastem (ShopVisualIconBrushWidget, pedzel TownManamgement.Shop.Icon.Brush) ma switch na 13 id gry; reszta = Default
    /// (warstwa ukryta - brak ikony).
    /// Naprawa: (1) w pamieci, raz na sesje, do pedzla Clan.Workshop.Type.Image dochodza style o nazwach typow bez ikony - kopie stylu
    /// najblizszej ikony gry (sprajty General\Icons\ShopIcons z ui_group1 - te same, ktorych gra juz uzywa; mlyn i stajnia jako nowe warstwy
    /// ze sprajtow mill_large / stable_large tego samego atlasu). Dane pedzla, nie kod widzetu - dziala tez w gotowym kodzie AutoGenerated.
    /// (2) postfiks ShopVisualIconBrushWidget.OnLateUpdate (wirtualna - bez ryzyka wlaczenia w kod wolajacego): gdy widzet po swojej inicjalizacji
    /// stoi w Default, a jego id ma odpowiednik - SetState(stan ikony gry). Brak celu = linia logu, potkniecia liczone, nic nie gasnie.
    /// </summary>
    internal static class WorkshopIcons
    {
        private const string ClanBrush = "Clan.Workshop.Type.Image";
        private const string ShopIcons = "General\\Icons\\ShopIcons\\";

        // id typu BK -> klucz ikony gry (nazwa stylu w Clan.Workshop.Type.Image / id w switchu TownManagement)
        private static readonly Dictionary<string, string> Known = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            { "weaponsmithy", "smithy" },
            { "armorsmithy", "smithy" },
            { "barding-smithy", "stable" },
            { "fletcher", "wood_WorkshopType" },
            { "bakery", "mill" },
            { "butcher", "tannery" },
            { "mines", "silversmithy" },
            { "meadery", "brewery" },
            { "artisans", "pottery_shop" },
            { "stable", "stable" },
        };

        // id ze switcha ShopVisualIconBrushWidget -> stan pedzla TownManamgement.Shop.Icon.Brush (dekompilacja 1.4.8)
        private static readonly Dictionary<string, string> TmStates = new Dictionary<string, string>
        {
            { "mill", "Mill" }, { "brewery", "Brewery" }, { "velvet_weavery", "VelvetWeavery" }, { "linen_weavery", "LinenWeavery" },
            { "wine_press", "WinePress" }, { "pottery_shop", "PotteryShop" }, { "olive_press", "OlivePress" }, { "wool_weavery", "WoolWeavery" },
            { "tannery", "Tannery" }, { "wood_WorkshopType", "WoodWorkshop" }, { "smithy", "Smithy" }, { "stable", "Stable" },
            { "silversmithy", "SilverSmithy" },
        };

        // nowe warstwy pedzla rodu dla ikon gry, ktorych ten pedzel nie ma (sprajty istnieja w NativeSpriteData, kategoria ui_group1)
        private static readonly Dictionary<string, string> ExtraLayers = new Dictionary<string, string>
        {
            { "mill", ShopIcons + "mill_large" },
            { "stable", ShopIcons + "stable_large" },
        };

        private static volatile Dictionary<string, string> _tm = new Dictionary<string, string>();
        private static readonly Dictionary<string, string> _fixed = new Dictionary<string, string>();
        private static bool _installed;
        private static int _stumbles;
        internal static string TmState = "nie instalowane";

        /// <summary>Postfiks ekranu miasta - raz na proces (OnBeforeInitialModuleScreenSetAsRoot).</summary>
        internal static void Install(Harmony h)
        {
            if (_installed) return;
            _installed = true;
            var t = AccessTools.TypeByName("TaleWorlds.MountAndBlade.GauntletUI.Widgets.Map.Menu.TownManagement.ShopVisualIconBrushWidget");
            MethodInfo m = t != null ? AccessTools.DeclaredMethod(t, "OnLateUpdate") : null;
            bool f1 = t != null && AccessTools.DeclaredField(t, "_shopId") != null, f2 = t != null && AccessTools.DeclaredField(t, "_initialized") != null;
            if (m == null || !f1 || !f2)
            {
                TmState = "NIE - brak celu w tej wersji gry (typ " + (t != null) + ", OnLateUpdate " + (m != null) + ", _shopId " + f1 + ", _initialized " + f2 + ") - ikony ekranu miasta jak w grze";
                Log.Info("Ikony warsztatow (463): " + TmState + ".");
                return;
            }
            h.Patch(m, postfix: new HarmonyMethod(typeof(WorkshopIcons), nameof(TmPost)));
            TmState = "postfiks ShopVisualIconBrushWidget.OnLateUpdate";
            Log.Info("Ikony warsztatow (463): " + TmState + " wpiety.");
        }

        private static void TmPost(object __instance, string ____shopId, bool ____initialized)
        {
            try
            {
                if (!____initialized || ____shopId == null) return;
                var map = _tm;
                string st;
                if (map.Count == 0 || !map.TryGetValue(____shopId, out st)) return;
                var w = __instance as Widget;
                if (w == null || w.CurrentState != "Default") return;
                w.SetState(st);
            }
            catch (Exception e)
            {
                if (++_stumbles <= 3) Log.Error("WorkshopIcons.TmPost (" + _stumbles + ")", e);
            }
        }

        /// <summary>Start sesji kampanii: style pedzla rodu + mapa ekranu miasta, jedna linia logu.</summary>
        internal static void Apply()
        {
            var types = WorkshopType.All;
            if (types == null) { Log.Info("Ikony warsztatow (463): NIECZYNNE - brak listy typow warsztatow."); return; }

            // ekran miasta: typy spoza switcha gry
            var tm = new Dictionary<string, string>();
            var tmLog = new List<string>();
            foreach (var wt in types)
            {
                if (wt == null || string.IsNullOrEmpty(wt.StringId) || TmStates.ContainsKey(wt.StringId)) continue;
                string key = KeyFor(wt.StringId), st;
                if (!TmStates.TryGetValue(key, out st)) continue;
                tm[wt.StringId] = st;
                tmLog.Add(wt.StringId + "->" + key);
            }
            _tm = tm;

            // pedzel rodu / encyklopedii / okna produkcji
            var clanLog = new List<string>();
            string clanNote = "";
            var bf = UIResourceManager.BrushFactory;
            Brush b = bf != null ? bf.GetBrush(ClanBrush) : null;
            if (b == null) clanNote = " | pedzel " + ClanBrush + " NIE znaleziony - bez zmian";
            else
            {
                foreach (var wt in types)
                {
                    if (wt == null || string.IsNullOrEmpty(wt.StringId)) continue;
                    string id = wt.StringId;
                    string used;
                    if (Good(b.GetStyle(id)))
                    {
                        // pedzel zyje caly proces - styl dopisany w poprzedniej sesji zostaje; linia mowi o nim dalej
                        if (_fixed.TryGetValue(id, out used)) clanLog.Add(id + "->" + used);
                        continue;
                    }
                    used = FixStyle(b, id, KeyFor(id));
                    if (used != null) _fixed[id] = used;
                    clanLog.Add(id + "->" + (used ?? "BRAK (zostaje prostokat)"));
                }
            }

            Log.Info("Ikony warsztatow (463): typow " + types.Count + " | rod/encyklopedia BK (bez ikony -> podstawiona): "
                + (clanLog.Count > 0 ? string.Join(", ", clanLog) : "wszystkie maja ikone") + clanNote
                + " | ekran miasta: " + (tmLog.Count > 0 ? string.Join(", ", tmLog) : "wszystkie w switchu gry") + " (" + TmState + ").");
        }

        // klucz ikony gry dla id typu: lista znanych, potem slowa w id, na koniec ogolny warsztat
        private static string KeyFor(string id)
        {
            string k;
            if (Known.TryGetValue(id, out k)) return k;
            string s = id.ToLowerInvariant();
            // 463-p: krotkie slowa (ore / ale / oil) tylko jako caly czlon id (podzial po _ i -) - fragment trafial w "store", "sale", "toil"
            var parts = new HashSet<string>(s.Split(new[] { '_', '-' }, StringSplitOptions.RemoveEmptyEntries));
            if (s.Contains("silver") || s.Contains("jewel") || s.Contains("gold") || s.Contains("mine") || parts.Contains("ore")) return "silversmithy";
            if (s.Contains("smith") || s.Contains("forge") || s.Contains("armor") || s.Contains("armour") || s.Contains("weapon")) return "smithy";
            if (s.Contains("brew") || s.Contains("mead") || parts.Contains("ale") || s.Contains("beer")) return "brewery";
            if (s.Contains("wine") || s.Contains("vine")) return "wine_press";
            if (s.Contains("olive") || parts.Contains("oil")) return "olive_press";
            if (s.Contains("velvet") || s.Contains("silk")) return "velvet_weavery";
            if (s.Contains("linen") || s.Contains("flax")) return "linen_weavery";
            if (s.Contains("wool") || s.Contains("weav") || s.Contains("cloth")) return "wool_weavery";
            if (s.Contains("tann") || s.Contains("leather") || s.Contains("hide") || s.Contains("butch")) return "tannery";
            if (s.Contains("pott") || s.Contains("clay")) return "pottery_shop";
            if (s.Contains("bake") || s.Contains("mill") || s.Contains("grain") || s.Contains("flour")) return "mill";
            if (s.Contains("stable") || s.Contains("horse") || s.Contains("bard")) return "stable";
            return "wood_WorkshopType";
        }

        // styl jest dobry, gdy ma widoczna warstwe ze sprajtem innym niz pusty kwadrat
        private static bool Good(Style st)
        {
            if (st == null) return false;
            foreach (var l in st.GetLayers())
            {
                if (l == null || l.IsHidden || l.Sprite == null) continue;
                string n = l.Sprite.Name;
                if (n != null && !n.StartsWith("BlankWhiteSquare", StringComparison.Ordinal)) return true;
            }
            return false;
        }

        // wzorzec: dowolny dobry styl ikony gry (wlasnosci tekstu / animacji jak w grze)
        private static Style Template(Brush b, out string visibleLayer)
        {
            visibleLayer = null;
            foreach (var k in new[] { "smithy", "brewery", "tannery", "wood_WorkshopType", "pottery_shop" })
            {
                var st = b.GetStyle(k);
                if (!Good(st)) continue;
                foreach (var l in st.GetLayers()) if (l != null && !l.IsHidden) { visibleLayer = l.Name; return st; }
            }
            return null;
        }

        // dopisuje (albo zastepuje zly) styl id; zwraca uzyty klucz ikony albo null
        private static string FixStyle(Brush b, string id, string key)
        {
            Style src = b.GetStyle(key);
            string layerToShow = null, used = key;
            if (!Good(src))
            {
                src = null;
                string sprite;
                if (ExtraLayers.TryGetValue(key, out sprite)) layerToShow = EnsureLayer(b, "arm463_" + key, sprite);
                if (layerToShow == null)
                {
                    // brak ikony docelowej - ogolny warsztat gry
                    used = Good(b.GetStyle("wood_WorkshopType")) ? "wood_WorkshopType" : (Good(b.GetStyle("smithy")) ? "smithy" : null);
                    if (used == null) return null;
                    src = b.GetStyle(used);
                }
            }
            Style st = new Style(b.Layers);
            st.DefaultStyle = b.DefaultStyle;
            if (src != null) st.FillFrom(src);
            else
            {
                string tplLayer;
                var tpl = Template(b, out tplLayer);
                if (tpl == null) return null;
                st.FillFrom(tpl);
                var hide = st.GetLayer(tplLayer);
                if (hide != null) hide.IsHidden = true;
                var show = st.GetLayer(layerToShow);
                if (show == null) return null;
                show.IsHidden = false;
            }
            st.Name = id;
            if (b.GetStyle(id) != null) b.RemoveStyle(id);
            b.AddStyle(st);
            return used;
        }

        // nowa warstwa pedzla ze sprajtem gry (kolor i dopasowanie z warstwy ikony gry); null gdy brak sprajtu albo wzorca
        private static string EnsureLayer(Brush b, string name, string sprite)
        {
            if (b.GetLayer(name) != null) return name;
            var data = UIResourceManager.SpriteData;
            var spr = data != null ? data.GetSprite(sprite) : null;
            if (spr == null) return null;
            BrushLayer from = null;
            foreach (var k in new[] { "smithy", "brewery", "tannery" }) { from = b.GetLayer(k); if (from != null && from.Sprite != null) break; from = null; }
            if (from == null) return null;
            var l = new BrushLayer();
            l.FillFrom(from);
            l.Name = name;
            l.Sprite = spr;
            l.IsHidden = true;
            b.AddLayer(l);
            return name;
        }
    }

    /// <summary>463: start sesji - ikony typow warsztatow (WorkshopIcons.Apply).</summary>
    internal class WorkshopIconsBehavior : CampaignBehaviorBase
    {
        public override void RegisterEvents()
        {
            CampaignEvents.OnSessionLaunchedEvent.AddNonSerializedListener(this, delegate (CampaignGameStarter s)
            {
                try { WorkshopIcons.Apply(); } catch (Exception e) { Log.Error("WorkshopIcons.Apply", e); }
            });
        }

        public override void SyncData(IDataStore dataStore) { }
    }
