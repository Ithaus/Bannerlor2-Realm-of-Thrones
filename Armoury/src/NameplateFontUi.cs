using System;
using System.Reflection;
using System.Runtime.CompilerServices;
using HarmonyLib;
using TaleWorlds.Engine.GauntletUI;
using TaleWorlds.GauntletUI;
using TaleWorlds.GauntletUI.BaseTypes;
using TaleWorlds.TwoDimension;

namespace Armoury
{
    /// <summary>
    /// m105-czcionki (Jeff 21.10: czcionki "bezpiecznie"): nazwy osad na mapie czcionka ROT "Game of Thrones" (ROT-Content/GUI/Fonts - 56 znakow: A-Z, a-z,
    /// spacja, #, apostrof; wszystkie 1066 nazw osad ROT sie mieszcza).
    /// Noc 21/22.10, dwie proby bez skutku (zrzuty 103a/103b): (1) kopie prefabow SettlementNameplateItem* w Armoury/GUI/Prefabs - przegrywaja z SandBox;
    /// (2) latka UIExtenderEx Brush.Font - tabliczki osad buduje gotowy kod SandBox.GauntletUI.AutoGenerated (nazwy dalej Galahad). Dlatego teraz kod:
    /// postfiks Harmony na SettlementNameplateWidget.UpdateNameplateTransparencyAndBrightness (gra woła go co klatke dla widocznej tabliczki i sama
    /// uzywa w nim SettlementNameTextWidget) - raz na tabliczke ustawia Brush.Font napisu (klon pedzla widzetu; style bez wlasnej czcionki biora ja
    /// z DefaultStyle). Odbicie bez typow widzetow gry; tabliczka zapamietana w ConditionalWeakTable (potem tylko jedno sprawdzenie). Klucz
    /// MapSettlementNamesRotFont czytany przy starcie gry (plik MCM albo ustawienia) - zmiana po ponownym uruchomieniu. Potkniecia licznikiem.
    /// </summary>
    internal static class NameplateFont
    {
        internal const string FontName = "Game of Thrones";
        private static bool _installed, _fontTried;
        private static Font _font;
        private static PropertyInfo _pItem, _pText;
        private static readonly ConditionalWeakTable<object, object> _done = new ConditionalWeakTable<object, object>();
        private static readonly object Mark = new object();
        private static int _set, _st;
        internal static string State = "nie instalowane";

        internal static void Install(Harmony h)
        {
            if (_installed) return;
            _installed = true;
            string src;
            if (!OnAtStart(out src))
            {
                State = "NIE - Map Settlement Names Rot Font wylaczone przy starcie gry (" + src + "); wlaczenie w MCM - po ponownym uruchomieniu gry";
                Log.Info("Czcionka nazw osad (m105): " + State + ".");
                return;
            }
            var t = AccessTools.TypeByName("TaleWorlds.MountAndBlade.GauntletUI.Widgets.Nameplate.SettlementNameplateWidget");
            var ti = AccessTools.TypeByName("TaleWorlds.MountAndBlade.GauntletUI.Widgets.Nameplate.SettlementNameplateItemWidget");
            MethodInfo m = t != null ? AccessTools.Method(t, "UpdateNameplateTransparencyAndBrightness") : null;
            _pItem = t != null ? AccessTools.Property(t, "NameplateItem") : null;
            _pText = ti != null ? AccessTools.Property(ti, "SettlementNameTextWidget") : null;
            if (m == null || _pItem == null || _pText == null)
            {
                State = "NIE - brak metody albo wlasciwosci tabliczki w tej wersji gry (metoda " + (m != null) + ", NameplateItem " + (_pItem != null) + ", SettlementNameTextWidget " + (_pText != null) + ") - nazwy jak w grze";
                Log.Info("Czcionka nazw osad (m105): " + State + ".");
                return;
            }
            h.Patch(m, postfix: new HarmonyMethod(typeof(NameplateFont), nameof(Post)));
            State = "postfiks SettlementNameplateWidget.UpdateNameplateTransparencyAndBrightness - nazwa osady czcionka " + FontName + " (klucz przy starcie: " + src + ")";
            Log.Info("Czcionka nazw osad (m105): " + State + ".");
        }

        private static void Post(object __instance)
        {
            try
            {
                if (__instance == null) return;
                object seen;
                if (_done.TryGetValue(__instance, out seen)) return;
                if (_font == null)
                {
                    if (_fontTried) return;
                    _fontTried = true;
                    _font = UIResourceManager.FontFactory != null ? UIResourceManager.FontFactory.GetFont(FontName) : null;
                    if (_font == null) { Log.Info("Czcionka nazw osad (m105): czcionki '" + FontName + "' brak w grze (ROT-Content) - nazwy jak w grze."); return; }
                }
                object item = _pItem.GetValue(__instance, null);
                if (item == null) return;
                var tw = _pText.GetValue(item, null) as TextWidget;
                if (tw == null) return;
                if (!ReferenceEquals(tw.ReadOnlyBrush.Font, _font)) tw.Brush.Font = _font;
                _done.Add(__instance, Mark);
                _set++;
                if (_set == 1) Log.Info("Czcionka nazw osad (m105): pierwsza tabliczka osady przestawiona na " + FontName + " (napis '" + tw.Text + "').");
            }
            catch (Exception e)
            {
                _st++;
                if (_st <= 3) Log.Error("NameplateFont.Post (potkniecie " + _st + ")", e);
            }
        }

        internal static string DayText() { return "tabliczki przestawione " + _set + ", potkniecia " + _st; }

        /// <summary>Klucz przy starcie gry: plik MCM (Configs/ModSettings/Global/Armoury/Armoury.json, wpis "MapSettlementNamesRotFont"), bez wpisu - Settings.Current.</summary>
        private static bool OnAtStart(out string src)
        {
            bool on = Settings.Current == null || Settings.Current.MapSettlementNamesRotFont;
            src = "ustawienia modulu / domyslne: " + (on ? "TAK" : "NIE");
            try
            {
                string doc = Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments);
                if (string.IsNullOrEmpty(doc)) return on;
                string f = System.IO.Path.Combine(doc, "Mount and Blade II Bannerlord", "Configs", "ModSettings", "Global", "Armoury", "Armoury.json");
                if (!System.IO.File.Exists(f)) return on;
                var mm = System.Text.RegularExpressions.Regex.Match(System.IO.File.ReadAllText(f), "\"MapSettlementNamesRotFont\"\\s*:\\s*(true|false)", System.Text.RegularExpressions.RegexOptions.IgnoreCase);
                if (!mm.Success) { src = "plik MCM bez wpisu, " + src; return on; }
                on = string.Equals(mm.Groups[1].Value, "true", StringComparison.OrdinalIgnoreCase);
                src = "plik MCM: " + (on ? "TAK" : "NIE");
            }
            catch (Exception e) { src = "plik MCM nieczytelny (" + e.GetType().Name + "), " + src; }
            return on;
        }
    }
}
